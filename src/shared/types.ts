/**
 * Types shared by the main process, the preload bridge and the renderer.
 * Keep this file free of Electron and DOM imports so all three can use it.
 */

export type Role = 'user' | 'assistant'

export interface ChatTurn {
  role: Role
  content: string
}

export interface Settings {
  /** Electron accelerator, e.g. "CommandOrControl+Shift+Space". */
  hotkey: string
  /** Base URL of the local Ollama server. */
  endpoint: string
  /** Ollama model tag. Needs to be vision-capable for screen questions. */
  model: string
  alwaysOnTop: boolean
  /** Longest edge, in pixels, the screenshot is downscaled to before it is sent to the model. */
  maxImageWidth: number
  /** Pressing the hotkey starts the microphone, transcribes locally, then asks. */
  voiceEnabled: boolean
}

export const DEFAULT_SETTINGS: Settings = {
  hotkey: 'CommandOrControl+Shift+Space',
  endpoint: 'http://127.0.0.1:11434',
  model: '',
  alwaysOnTop: true,
  maxImageWidth: 1280,
  voiceEnabled: true
}

export interface VoiceStatus {
  ready: boolean
  binaryPath: string | null
  modelPath: string
  modelPresent: boolean
  modelBytes: number
  error?: string
}

export interface VoiceProgressEvent {
  phase: 'download' | 'ready'
  receivedBytes?: number
  totalBytes?: number
  fraction?: number
}

export interface HotkeyState {
  accelerator: string
  registered: boolean
  error?: string
}

export interface OllamaModel {
  name: string
  sizeBytes: number
  modifiedAt?: string
  /** Best-effort guess from the model tag; Ollama does not expose capabilities. */
  vision: boolean
}

export interface OllamaStatus {
  online: boolean
  version?: string
  error?: string
  models: OllamaModel[]
}

export interface ScreenShotInfo {
  /** Downscaled JPEG as a data URL, for the preview in the panel. */
  dataUrl: string
  displayLabel: string
  width: number
  height: number
  /** Cursor position normalised to 0..1 inside the captured image. */
  cursor: { x: number; y: number } | null
  capturedAt: number
  source: 'hotkey' | 'manual'
}

export interface AskRequest {
  /** Generated by the renderer so token events can be matched before the invoke resolves. */
  id: string
  prompt: string
  history: ChatTurn[]
  useScreen: boolean
}

export interface AskTokenEvent {
  id: string
  token: string
}

export interface AskDoneEvent {
  id: string
  text: string
}

export interface AskErrorEvent {
  id: string
  message: string
  cancelled?: boolean
}

export interface Bootstrap {
  platform: string
  settings: Settings
  hotkey: HotkeyState
}

export interface SaveResult {
  settings: Settings
  hotkey: HotkeyState
}

/** Shape of `window.rex`, injected by the preload script. */
export interface RexApi {
  platform: string
  bootstrap(): Promise<Bootstrap>
  saveSettings(patch: Partial<Settings>): Promise<SaveResult>
  ollamaStatus(): Promise<OllamaStatus>
  capture(): Promise<ScreenShotInfo>
  ask(request: AskRequest): Promise<{ ok: true }>
  cancel(id: string): Promise<void>
  hide(): Promise<void>
  quit(): Promise<void>

  voiceStatus(): Promise<VoiceStatus>
  prepareVoice(): Promise<VoiceStatus>
  openMicrophoneSettings(): Promise<void>
  transcribe(samples: Float32Array): Promise<{ text: string }>

  onVoiceBegin(cb: () => void): () => void
  onVoiceError(cb: (payload: { message: string }) => void): () => void
  onVoiceProgress(cb: (event: VoiceProgressEvent) => void): () => void

  onScreen(cb: (info: ScreenShotInfo) => void): () => void
  onCaptureStarted(cb: () => void): () => void
  onCaptureError(cb: (payload: { message: string }) => void): () => void
  onNewChat(cb: () => void): () => void
  onAskToken(cb: (event: AskTokenEvent) => void): () => void
  onAskDone(cb: (event: AskDoneEvent) => void): () => void
  onAskError(cb: (event: AskErrorEvent) => void): () => void
  onHotkeyState(cb: (state: HotkeyState) => void): () => void
  onFocusComposer(cb: () => void): () => void
  onOpenSettings(cb: () => void): () => void
}
